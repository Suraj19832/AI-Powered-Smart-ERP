const TABS = ['forecast', 'reorder', 'reports']

export default function InsightsPage() {
  const [params, setParams] = useSearchParams()
  const tab = Math.max(0, TABS.indexOf(params.get('tab') ?? 'forecast'))
  return (
    <>
      <PageHeader title="AI Insights" subtitle="Demand forecasting, smart inventory and AI-written business reports" />
      <Tabs value={tab} onChange={(_, v) => setParams({ tab: TABS[v] })} sx={{ mb: 2 }} variant="scrollable" allowScrollButtonsMobile>
        <Tab label="Sales forecast" /><Tab label="Smart reorder" /><Tab label="AI report generator" />
      </Tabs>
      {tab === 0 && <ForecastTab />}
      {tab === 1 && <ReorderTab />}
      {tab === 2 && <ReportsTab />}
    </>
  )
}

function AiCommentary({ url, label }: { url: string; label: string }) {
  const [load, { data, isFetching, error }] = useLazyGet<Narrative>()
  return (
    <SectionCard
      title={<Stack direction="row" spacing={1} sx={{ alignItems: 'center' }}><AutoAwesomeIcon color="secondary" fontSize="small" /><Typography sx={{ fontWeight: 700 }}>AI commentary</Typography></Stack>}
      action={<Button size="small" variant="outlined" onClick={() => load(url)} disabled={isFetching}>{isFetching ? 'Thinking…' : data ? 'Regenerate' : label}</Button>}
    >
      {error ? <Alert severity="error">{errorMessage(error)}</Alert> : data ? (
        <>
          <Markdown>{data.markdown}</Markdown>
          <Typography variant="caption" color="text.secondary">{data.mode === 'openai' ? 'Written by OpenAI from computed figures' : 'Generated by the built-in rules engine (offline mode)'}</Typography>
        </>
      ) : <Typography variant="body2" color="text.secondary">Get a plain-English interpretation of the numbers on this page.</Typography>}
    </SectionCard>
  )
}

function ForecastTab() {
  const [product, setProduct] = useState<Lookup | null>(null)
  const [months, setMonths] = useState(6)
  const { data: products = [] } = useGet<Lookup[]>('/products/lookup')
  const { data, isFetching, error } = useGet<Forecast>('/ai/forecast', { productId: product?.id, months })
  const { data: productForecasts } = useGet<ProductForecast[]>('/ai/forecast/products', { take: 10 })
  const c = useChart()
  const axis = { stroke: c.axis, tick: { fill: c.muted, fontSize: 12 }, tickLine: false }
  const isQty = !!product
  const fmt = isQty ? (v: number) => `${num(v)} units` : money

  const chartData = (data?.points ?? []).map((p) => ({ ...p, band: p.lower !== null && p.lower !== undefined ? [p.lower, p.upper] : null }))

  return (
    <Box sx={{ display: 'grid', gap: 2 }}>
      <Stack direction={{ xs: 'column', md: 'row' }} spacing={1.5}>
        <Autocomplete sx={{ minWidth: 320 }} options={products} value={product} onChange={(_, v) => setProduct(v)}
          getOptionLabel={(o) => o.name} renderInput={(p) => <TextField {...p} label="Product (leave empty for total sales)" />} />
        <TextField select label="Horizon" value={months} onChange={(e) => setMonths(Number(e.target.value))} sx={{ minWidth: 140 }}>
          {[3, 6, 12].map((m) => <MenuItem key={m} value={m}>{m} months</MenuItem>)}
        </TextField>
      </Stack>
      <ErrorAlert error={error} />
      {data && (
        <Box sx={{ display: 'grid', gridTemplateColumns: { xs: '1fr', sm: 'repeat(3, 1fr)' }, gap: 2 }}>
          <Card><CardContent><Typography variant="body2" color="text.secondary">Next month forecast</Typography><Typography variant="h5">{fmt(data.nextMonthForecast)}</Typography></CardContent></Card>
          <Card><CardContent><Typography variant="body2" color="text.secondary">Trend per month</Typography><Typography variant="h5" color={data.trendPercentPerMonth >= 0 ? 'success.main' : 'error.main'}>{pct(data.trendPercentPerMonth)}</Typography></CardContent></Card>
          <Card><CardContent>
            <MuiTooltip title="Mean absolute percentage error of one-step-ahead predictions on historical months (lower is better)">
              <Typography variant="body2" color="text.secondary">Back-test error (MAPE)</Typography>
            </MuiTooltip>
            <Typography variant="h5">{data.meanAbsolutePercentError.toFixed(1)}%</Typography>
          </CardContent></Card>
        </Box>
      )}
      <Box sx={{ display: 'grid', gridTemplateColumns: { xs: '1fr', lg: '2fr 1fr' }, gap: 2 }}>
        <SectionCard title={data ? `${data.metric} — ${data.target}` : 'Forecast'} action={data && <Typography variant="caption" color="text.secondary">{data.method}</Typography>}>
          {isFetching && !data ? <Loading /> : (
            <>
              <Legend items={[{ label: 'Actual', color: c.series[0] }, { label: 'Forecast', color: c.series[1], dashed: true }, { label: '80% range', color: c.series[1] }]} />
              <ResponsiveContainer width="100%" height={320}>
                <ComposedChart data={chartData} margin={{ top: 8, right: 12, left: 0, bottom: 0 }}>
                  <CartesianGrid vertical={false} stroke={c.grid} />
                  <XAxis dataKey="month" tickFormatter={monthLabel} {...axis} />
                  <YAxis tickFormatter={(v) => (isQty ? num(v) : moneyCompact(v))} {...axis} axisLine={false} width={70} />
                  <Tooltip content={<ChartTooltip format={fmt} labelFormat={monthLabel} />} cursor={{ stroke: c.axis }} />
                  <Area dataKey="band" name="Range" stroke="none" fill={c.series[1]} fillOpacity={0.15} isAnimationActive={false} tooltipType="none" />
                  <Line dataKey="actual" name="Actual" stroke={c.series[0]} strokeWidth={2} dot={false} activeDot={{ r: 5, stroke: c.surface, strokeWidth: 2 }} connectNulls={false} />
                  <Line dataKey="forecast" name="Forecast" stroke={c.series[1]} strokeWidth={2} strokeDasharray="6 4" dot={{ r: 3 }} activeDot={{ r: 5, stroke: c.surface, strokeWidth: 2 }} />
                </ComposedChart>
              </ResponsiveContainer>
            </>
          )}
        </SectionCard>
        <AiCommentary url="/ai/forecast/commentary" label="Explain forecast" />
      </Box>
      <SectionCard title="Top products — demand outlook">
        <Box sx={{ overflowX: 'auto' }}>
          <Table size="small">
            <TableHead><TableRow><TableCell>Product</TableCell><TableCell align="right">Avg / month</TableCell><TableCell align="right">Next month</TableCell><TableCell align="right">Next 3 months</TableCell><TableCell align="right">Trend</TableCell><TableCell align="right">On hand</TableCell><TableCell align="right">Months of cover</TableCell></TableRow></TableHead>
            <TableBody>
              {(productForecasts ?? []).map((p) => (
                <TableRow key={p.productId} hover sx={{ cursor: 'pointer' }} onClick={() => setProduct({ id: p.productId, name: p.name })}>
                  <TableCell>{p.name}</TableCell><TableCell align="right">{num(p.avgMonthlyQty)}</TableCell><TableCell align="right">{num(p.nextMonthQty)}</TableCell>
                  <TableCell align="right">{num(p.next3MonthsQty)}</TableCell>
                  <TableCell align="right" sx={{ color: p.trendPercentPerMonth >= 0 ? 'success.main' : 'error.main' }}>{pct(p.trendPercentPerMonth)}</TableCell>
                  <TableCell align="right">{num(p.quantityOnHand)} {p.unit}</TableCell>
                  <TableCell align="right" sx={{ fontWeight: 600, color: (p.monthsOfCover ?? 99) < 1 ? 'error.main' : undefined }}>{p.monthsOfCover === null || p.monthsOfCover === undefined ? '—' : num(p.monthsOfCover)}</TableCell>
                </TableRow>
              ))}
            </TableBody>
          </Table>
        </Box>
      </SectionCard>
    </Box>
  )
}

function ReorderTab() {
  const { data, isLoading, error } = useGet<ReorderSuggestion[]>('/ai/reorder-suggestions')
  const { data: products = [] } = useGet<Lookup[]>('/products/lookup')
  const navigate = useNavigate()
  const canBuy = useHasRole(...R.buy)
  if (isLoading) return <Loading label="Analysing demand and stock levels…" />
  if (!data) return <ErrorAlert error={error} />

  const groups = Object.values(data.reduce<Record<string, { supplierId: number | null; name: string; items: ReorderSuggestion[] }>>((acc, s) => {
    const k = String(s.supplierId ?? 'none')
    acc[k] ??= { supplierId: s.supplierId ?? null, name: s.supplierName ?? 'No preferred supplier', items: [] }
    acc[k].items.push(s)
    return acc
  }, {}))

  const createPo = (g: (typeof groups)[number]) => {
    const prefill: OrderPrefill = {
      partyId: g.supplierId,
      notes: 'Created from AI smart reorder suggestions',
      lines: g.items.map((s) => ({
        productId: s.productId, quantity: s.suggestedQuantity,
        unitPrice: s.suggestedQuantity ? Math.round((s.estimatedCost / s.suggestedQuantity) * 100) / 100 : 0,
        taxRate: products.find((p) => p.id === s.productId)?.taxRate ?? 0,
      })),
    }
    navigate('/purchase-orders/new', { state: { prefill } })
  }

  return (
    <Box sx={{ display: 'grid', gap: 2 }}>
      <Alert severity="info" icon={<AutoAwesomeIcon />}>
        Suggestions use 90-day demand, demand variability (95% service-level safety stock), supplier lead times and stock already on order.
      </Alert>
      <Box sx={{ display: 'grid', gridTemplateColumns: { xs: '1fr', lg: '2fr 1fr' }, gap: 2, alignItems: 'start' }}>
        <Box sx={{ display: 'grid', gap: 2 }}>
          {groups.length === 0 && <Card><CardContent><Typography>Nothing needs reordering right now. 🎉</Typography></CardContent></Card>}
          {groups.map((g) => (
            <SectionCard key={g.name} title={`${g.name} — ${money(g.items.reduce((s, i) => s + i.estimatedCost, 0))}`}
              action={canBuy && g.supplierId && <Button size="small" variant="contained" startIcon={<AddShoppingCartIcon />} onClick={() => createPo(g)}>Create PO</Button>}>
              <Box sx={{ overflowX: 'auto' }}>
                <Table size="small">
                  <TableHead><TableRow><TableCell>Product</TableCell><TableCell>Urgency</TableCell><TableCell align="right">On hand</TableCell><TableCell align="right">Days cover</TableCell><TableCell align="right">Order qty</TableCell><TableCell align="right">Est. cost</TableCell></TableRow></TableHead>
                  <TableBody>
                    {g.items.map((s) => (
                      <TableRow key={s.productId}>
                        <TableCell>
                          <MuiTooltip title={s.reason}><Box><Typography variant="body2" sx={{ fontWeight: 500 }}>{s.name}</Typography>
                            <Typography variant="caption" color="text.secondary">{s.reason}</Typography></Box></MuiTooltip>
                        </TableCell>
                        <TableCell><StatusChip status={s.urgency} /></TableCell>
                        <TableCell align="right">{num(s.quantityOnHand)}{s.onOrder > 0 && <Typography variant="caption" color="text.secondary" sx={{ display: 'block' }}>+{num(s.onOrder)} on order</Typography>}</TableCell>
                        <TableCell align="right">{s.daysOfCover === null || s.daysOfCover === undefined ? '—' : num(s.daysOfCover)}</TableCell>
                        <TableCell align="right" sx={{ fontWeight: 700 }}>{num(s.suggestedQuantity)} {s.unit}</TableCell>
                        <TableCell align="right">{money(s.estimatedCost)}</TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
              </Box>
            </SectionCard>
          ))}
        </Box>
        <AiCommentary url="/ai/reorder-suggestions/commentary" label="Prioritise for me" />
      </Box>
    </Box>
  )
}

const REPORT_TYPES = [
  { value: 'business-overview', label: 'Business insights overview' },
  { value: 'monthly-sales', label: 'Monthly sales summary' },
  { value: 'purchase', label: 'Purchase report' },
  { value: 'inventory', label: 'Inventory health report' },
]

function ReportsTab() {
  const [type, setType] = useState('business-overview')
  const [month, setMonth] = useState(dayjs().format('YYYY-MM'))
  const [generate, { data, isLoading, error }] = useAiReportMutation()
  const canReport = useHasRole(...R.reports)

  if (!canReport) return <Alert severity="warning">Report generation is available to Admin, Manager and Accountant roles.</Alert>

  const download = () => {
    if (!data) return
    const url = URL.createObjectURL(new Blob([data.markdown], { type: 'text/markdown' }))
    const a = document.createElement('a'); a.href = url; a.download = `${data.title.replace(/[^\w]+/g, '-')}.md`; a.click(); URL.revokeObjectURL(url)
  }

  return (
    <Box sx={{ display: 'grid', gap: 2 }}>
      <Card><CardContent>
        <Stack direction={{ xs: 'column', md: 'row' }} spacing={1.5} sx={{ alignItems: { md: 'center' } }}>
          <TextField select label="Report" value={type} onChange={(e) => setType(e.target.value)} sx={{ minWidth: 260 }}>
            {REPORT_TYPES.map((r) => <MenuItem key={r.value} value={r.value}>{r.label}</MenuItem>)}
          </TextField>
          <TextField label="Month" type="month" value={month} onChange={(e) => setMonth(e.target.value)} disabled={type === 'inventory'} slotProps={{ inputLabel: { shrink: true } }} />
          <Button variant="contained" startIcon={<AutoAwesomeIcon />} disabled={isLoading} onClick={() => generate({ type, month })}>
            {isLoading ? 'Generating…' : 'Generate report'}
          </Button>
        </Stack>
      </CardContent></Card>
      {error && <Alert severity="error">{errorMessage(error)}</Alert>}
      {isLoading && <Loading label="Collecting figures and writing the report…" />}
      {data && !isLoading && (
        <SectionCard
          title={data.title}
          action={<Stack direction="row" spacing={1}>
            <Button size="small" startIcon={<DownloadIcon />} onClick={download}>Markdown</Button>
            <Button size="small" startIcon={<PrintIcon />} onClick={() => window.print()}>Print</Button>
          </Stack>}
        >
          <Markdown>{data.markdown}</Markdown>
          <Typography variant="caption" color="text.secondary">
            Generated {dayjs(data.generatedAt).format('DD MMM YYYY HH:mm')} · {data.mode === 'openai' ? 'written by OpenAI from figures computed by SmartERP' : 'built-in template (offline mode)'}
          </Typography>
        </SectionCard>
      )}
    </Box>
  )
}
